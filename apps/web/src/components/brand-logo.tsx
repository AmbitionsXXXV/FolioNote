const BRAND_LOGOS = {
  notion: NotionLogo,
  "google-docs": GoogleDocsLogo,
  claude: ClaudeLogo,
  openai: OpenAILogo,
  gemini: GeminiLogo,
  deepseek: DeepSeekLogo,
  qwen: QwenLogo,
  kimi: KimiLogo,
  grok: GrokLogo
} as const

export type Brand = keyof typeof BRAND_LOGOS

export function BrandLogo({
  brand,
  className
}: {
  brand: Brand
  className?: string
}) {
  const Logo = BRAND_LOGOS[brand]
  return <Logo className={className} />
}

/** Catalog ids (model-list) and BYOK ids (constants) both resolve here. */
const PROVIDER_BRANDS: Record<string, Brand> = {
  anthropic: "claude",
  claude: "claude",
  openai: "openai",
  google: "gemini",
  gemini: "gemini",
  deepseek: "deepseek",
  qwen: "qwen",
  moonshot: "kimi",
  xai: "grok"
}

/**
 * An LLM provider's mark. Providers without a known brand fall back to their
 * catalog logo URL, then to their initials.
 */
export function ProviderLogo({
  id,
  name,
  logo,
  className
}: {
  id: string
  name: string
  logo?: string | null
  className?: string
}) {
  const brand = PROVIDER_BRANDS[id]
  if (brand) {
    return <BrandLogo brand={brand} className={className} />
  }
  if (logo) {
    return <img alt="" aria-hidden="true" className={className} src={logo} />
  }
  return (
    <span
      aria-hidden="true"
      className={`inline-flex items-center justify-center text-[0.6em] font-bold ${className ?? ""}`}
    >
      {name.slice(0, 2).toUpperCase()}
    </span>
  )
}
