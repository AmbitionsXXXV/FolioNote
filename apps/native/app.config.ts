import { cpSync, existsSync, readdirSync } from "node:fs"
import { join } from "node:path"

import type { ExpoConfig } from "expo/config"
import { withDangerousMod } from "expo/config-plugins"
import type { ConfigPlugin } from "expo/config-plugins"

import pkg from "./package.json"

const SOURCE_DIR = "assets/tab-icons"
const ASSET_FOLDER = /\.(symbolset|imageset)$/

/**
 * Inlined because the Expo config loader cannot resolve extensionless
 * relative TypeScript imports.
 *
 * Copies the custom tab icons (SF Symbol templates for the resting state,
 * duotone vector images for the selected state) into the iOS asset catalog
 * on prebuild, so NativeTabs can reference them with `xcasset`.
 *
 * The sources are generated by the glyph script; see assets/tab-icons.
 */
const withTabIcons: ConfigPlugin = (config) =>
  withDangerousMod(config, [
    "ios",
    (modConfig) => {
      const { platformProjectRoot, projectName, projectRoot } =
        modConfig.modRequest
      const source = join(projectRoot, SOURCE_DIR)
      const catalog = join(
        platformProjectRoot,
        projectName ?? "",
        "Images.xcassets"
      )

      if (!existsSync(catalog)) {
        throw new Error(
          `with-tab-icons: asset catalog not found at ${catalog}; tab icons were not installed`
        )
      }

      for (const entry of readdirSync(source)) {
        if (ASSET_FOLDER.test(entry)) {
          cpSync(join(source, entry), join(catalog, entry), {
            recursive: true
          })
        }
      }

      return Promise.resolve(modConfig)
    }
  ])

